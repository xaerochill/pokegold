GoldenrodGymWhitneyScript:
	faceplayer
	opentext
	checkevent EVENT_BEAT_WHITNEY
	iftrue .FightDone
	opentext
	writetext WhitneyIntroText
	waitbutton
	closetext
	winlosstext WhitneyWinText, WhitneyLossText
	loadtrainer WHITNEY, WHITNEY1
	startbattle
	reloadmapafterbattle
	opentext
	writetext ReceivedPlainBadgeText
	playsound SFX_GET_BADGE
	waitsfx
	setflag ENGINE_PLAINBADGE
	special RecalcObedienceLevel
	readvar VAR_BADGES
	scall GoldenrodGymActivateRockets
.FightDone:
	checktmhm TM_ATTRACT
	iftrue .Rematch
	setevent EVENT_BEAT_WHITNEY
	setevent EVENT_BEAT_BEAUTY_VICTORIA
	setevent EVENT_BEAT_BEAUTY_SAMANTHA
	setevent EVENT_BEAT_LASS_CARRIE
	setevent EVENT_BEAT_LASS_BRIDGET
	writetext WhitneyPlainBadgeText
	promptbutton
	verbosegivetmhm TM_ATTRACT
	writetext WhitneyTMAttractText
	waitbutton
	closetext
	turnobject PLAYER, DOWN
	end

.Rematch:
	writetext WhitneyFightDoneText
	yesorno
	iffalse .End
	writetext WhitneyRematchText
	waitbutton
	closetext
	winlosstext WhitneyWinText, WhitneyLossText
	loadtrainer WHITNEY, WHITNEY1
	startbattle
	reloadmapafterbattle
	turnobject PLAYER, DOWN
	end

.End:
	closetext
	turnobject PLAYER, DOWN
	end

